const dictionaries: Record<Locale, Record<string, string>> = { en, 'pt-BR': ptBR };

let current: Locale = detectLocale();
const listeners = new Set<() => void>();

export function detectLocale(): Locale {
  if (typeof navigator === 'undefined') return 'en';
  const stored = localStorage.getItem('voxorbita.locale');
  if (stored === 'en' || stored === 'pt-BR') return stored;
  return navigator.language.toLowerCase().startsWith('pt') ? 'pt-BR' : 'en';
}

export function getLocale(): Locale {
  return current;
}

export function setLocale(locale: Locale): void {
  current = locale;
  localStorage.setItem('voxorbita.locale', locale);
  document.documentElement.lang = locale === 'pt-BR' ? 'pt-BR' : 'en';
  for (const fn of listeners) fn();
}

/** Subscribe to locale changes (UI re-render). */
export function onLocaleChange(fn: () => void): void {
  listeners.add(fn);
}

export function t(key: string, params?: Record<string, string>): string {
  let s = dictionaries[current][key] ?? en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, v);
  return s;
}

/** Label for a config field: cfg.<key>, falling back to a title-cased key. */
export function fieldLabel(key: string): string {
  const k = `cfg.${key}`;
  const hit = dictionaries[current][k] ?? en[k];
  if (hit) return hit;
  return key.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase());
}
